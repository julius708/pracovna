/** The hook row of a code ("A140" -> 'A'); the board colours rows A/B/C/D. */
export function keyRow(code: string): 'A' | 'B' | 'C' | 'D' | null {
  const r = code.trim().charAt(0).toUpperCase();
  return r === 'A' || r === 'B' || r === 'C' || r === 'D' ? r : null;
}
